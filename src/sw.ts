/// <reference lib="webworker" />
import { precacheAndRoute, cleanupOutdatedCaches, createHandlerBoundToURL } from "workbox-precaching";
import { registerRoute, NavigationRoute } from "workbox-routing";
import { CacheFirst, StaleWhileRevalidate } from "workbox-strategies";
import { clientsClaim } from "workbox-core";
import { ExpirationPlugin } from "workbox-expiration";
import { CacheableResponsePlugin } from "workbox-cacheable-response";

declare let self: ServiceWorkerGlobalScope;

// Activate new service worker immediately without waiting for existing tabs to close
self.skipWaiting();
clientsClaim();

// Cleanup old cache versions automatically
cleanupOutdatedCaches();

// Precache essential static shell assets generated by Vite
precacheAndRoute(self.__WB_MANIFEST || []);

// Navigation route with explicit denylist for server-rendered endpoints
const navigationHandler = createHandlerBoundToURL("/index.html");
const navigationRoute = new NavigationRoute(navigationHandler, {
  denylist: [/^\/api\//, /^\/p\//, /^\/healthz/, /^\/metrics/],
});
registerRoute(navigationRoute);

// Cache Google Fonts stylesheets with StaleWhileRevalidate
registerRoute(
  ({ url }) => url.origin === "https://fonts.googleapis.com",
  new StaleWhileRevalidate({
    cacheName: "google-fonts-stylesheets",
  })
);

// Cache Google Fonts webfont files with CacheFirst (1 year)
registerRoute(
  ({ url }) => url.origin === "https://fonts.gstatic.com",
  new CacheFirst({
    cacheName: "google-fonts-webfonts",
    plugins: [
      new CacheableResponsePlugin({
        statuses: [0, 200],
      }),
      new ExpirationPlugin({
        maxAgeSeconds: 60 * 60 * 24 * 365, // 1 year
        maxEntries: 30,
      }),
    ],
  })
);

// Runtime caching for immutable hashed assets (downloaded on demand per role)
// Restrict strictly to same-origin to prevent pinning third-party SDKs (e.g. Cashfree)
registerRoute(
  ({ request, url }) =>
    url.origin === self.location.origin &&
    (request.destination === "script" ||
      request.destination === "style" ||
      url.pathname.startsWith("/assets/")) &&
    !url.pathname.startsWith("/api/"),
  new CacheFirst({
    cacheName: "pg-assets-cache",
    plugins: [
      new ExpirationPlugin({
        maxEntries: 100,
        maxAgeSeconds: 30 * 24 * 60 * 60, // 30 days
        purgeOnQuotaError: true,
      }),
    ],
  })
);

// Web Push event listener
self.addEventListener("push", (event) => {
  let data: { title?: string; body?: string; icon?: string; badge?: string; url?: string } = {
    title: "PG Cashflow",
    body: "You have a new update.",
  };

  if (event.data) {
    try {
      data = event.data.json();
    } catch {
      data = { title: "PG Cashflow", body: event.data.text() };
    }
  }

  // Only same-origin deep links are honoured; anything else falls back to the app root.
  let safeUrl = "/";
  try {
    const parsed = new URL(data.url || "/", self.location.origin);
    if (parsed.origin === self.location.origin) {
      safeUrl = parsed.pathname + parsed.search + parsed.hash;
    }
  } catch {
    safeUrl = "/";
  }

  const options = {
    body: data.body || "",
    icon: "/pwa-192x192.png",
    badge: "/pwa-192x192.png",
    data: safeUrl,
    vibrate: [200, 100, 200],
  } as unknown as NotificationOptions;

  event.waitUntil(self.registration.showNotification(data.title || "PG Cashflow", options));
});

// Notification click event listener
self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const urlToOpen = (event.notification.data as string) || "/";

  event.waitUntil(
    self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((windowClients) => {
      for (const client of windowClients) {
        if (new URL(client.url).pathname === new URL(urlToOpen, self.location.origin).pathname && "focus" in client) {
          return client.focus();
        }
      }
      if (self.clients.openWindow) {
        return self.clients.openWindow(urlToOpen);
      }
    })
  );
});
